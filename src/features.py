"""Feature engineering and preprocessing pipelines for churn-mlops-platform.

Encapsulates feature engineering, numerical scaling, categorical encoding,
and missing value imputation within scikit-learn Pipeline and ColumnTransformer
objects to guarantee zero data leakage between train and test splits.
"""

from pathlib import Path
import sys
from typing import Any, Dict, List, Optional, Tuple, Union
import numpy as np
import pandas as pd
from sklearn.base import BaseEstimator, TransformerMixin
from sklearn.compose import ColumnTransformer
from sklearn.impute import SimpleImputer
from sklearn.pipeline import Pipeline
from sklearn.preprocessing import OneHotEncoder, StandardScaler

# Ensure repository root is on sys.path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from src.config import (
    CATEGORICAL_COLS,
    NUMERICAL_COLS,
    SERVICE_COLS,
    setup_logger,
)

logger = setup_logger(__name__)

# Additional columns generated by TelcoFeatureEngineer
ENGINEERED_NUMERICAL_COLS: List[str] = [
    "charges_per_tenure",
    "num_services",
    "monthly_to_total_ratio",
]

ENGINEERED_CATEGORICAL_COLS: List[str] = [
    "tenure_bucket",
    "has_streaming",
    "has_security_backup",
]


class TelcoFeatureEngineer(BaseEstimator, TransformerMixin):
    """Custom scikit-learn transformer for Telco customer churn feature engineering.

    Creates domain-specific interaction features:
        1. tenure_bucket: Discretized customer tenure into contractual tiers.
        2. charges_per_tenure: TotalCharges divided by (tenure + 1).
        3. monthly_to_total_ratio: Ratio of MonthlyCharges to TotalCharges.
        4. num_services: Count of active auxiliary services subscribed.
        5. has_streaming: Flag indicating StreamingTV or StreamingMovies.
        6. has_security_backup: Flag indicating OnlineSecurity or OnlineBackup.
    """

    def __init__(self) -> None:
        pass

    def fit(self, X: Union[pd.DataFrame, Dict[str, Any]], y: Optional[Any] = None) -> "TelcoFeatureEngineer":
        """Stateless fit conforming to scikit-learn transformer API.

        Args:
            X: Input dataframe or dict.
            y: Ignored target.

        Returns:
            self
        """
        return self

    def transform(self, X: Union[pd.DataFrame, Dict[str, Any], List[Dict[str, Any]]]) -> pd.DataFrame:
        """Transforms input data by imputing types and computing engineered features.

        Args:
            X: Input dataframe or dictionary representation.

        Returns:
            pd.DataFrame: Augmented DataFrame with domain engineered features.
        """
        if isinstance(X, dict):
            df = pd.DataFrame([X])
        elif isinstance(X, list):
            df = pd.DataFrame(X)
        elif isinstance(X, pd.DataFrame):
            df = X.copy()
        else:
            df = pd.DataFrame(X)

        # Standardize TotalCharges
        if "TotalCharges" in df.columns:
            df["TotalCharges"] = pd.to_numeric(
                df["TotalCharges"].astype(str).str.strip(),
                errors="coerce",
            )
            df["TotalCharges"] = df["TotalCharges"].fillna(0.0)
        else:
            df["TotalCharges"] = 0.0

        if "tenure" in df.columns:
            df["tenure"] = pd.to_numeric(df["tenure"], errors="coerce").fillna(0).astype(float)
        else:
            df["tenure"] = 0.0

        if "MonthlyCharges" in df.columns:
            df["MonthlyCharges"] = pd.to_numeric(df["MonthlyCharges"], errors="coerce").fillna(0.0).astype(float)
        else:
            df["MonthlyCharges"] = 0.0

        # 1. Tenure Buckets
        bins = [-1, 12, 24, 48, 60, 120]
        labels = ["0-12m", "13-24m", "25-48m", "49-60m", "60m+"]
        df["tenure_bucket"] = pd.cut(df["tenure"], bins=bins, labels=labels).astype(str)

        # 2. Charges per Tenure Month
        df["charges_per_tenure"] = df["TotalCharges"] / (df["tenure"] + 1.0)

        # 3. Monthly to Total Ratio
        df["monthly_to_total_ratio"] = df["MonthlyCharges"] / (df["TotalCharges"] + 1.0)

        # 4. Number of Subscribed Services
        active_services = pd.Series(0, index=df.index)
        for col in SERVICE_COLS:
            if col in df.columns:
                active_services += (df[col].astype(str).str.strip().str.lower() == "yes").astype(int)
        df["num_services"] = active_services

        # 5. Compound Streaming indicator
        has_tv = df["StreamingTV"].astype(str).str.lower() == "yes" if "StreamingTV" in df.columns else False
        has_mov = df["StreamingMovies"].astype(str).str.lower() == "yes" if "StreamingMovies" in df.columns else False
        df["has_streaming"] = np.where(has_tv | has_mov, "Yes", "No")

        # 6. Compound Security / Backup indicator
        has_sec = df["OnlineSecurity"].astype(str).str.lower() == "yes" if "OnlineSecurity" in df.columns else False
        has_bck = df["OnlineBackup"].astype(str).str.lower() == "yes" if "OnlineBackup" in df.columns else False
        df["has_security_backup"] = np.where(has_sec | has_bck, "Yes", "No")

        return df


def get_all_feature_columns() -> Tuple[List[str], List[str]]:
    """Returns the combined lists of numerical and categorical column names.

    Returns:
        Tuple[List[str], List[str]]: (all_numerical_cols, all_categorical_cols)
    """
    all_num = NUMERICAL_COLS + ENGINEERED_NUMERICAL_COLS
    all_cat = CATEGORICAL_COLS + ENGINEERED_CATEGORICAL_COLS
    return all_num, all_cat


def get_preprocessing_steps() -> List[Tuple[str, Any]]:
    """Constructs the sequence of preprocessing and feature engineering steps.

    Returns:
        List[Tuple[str, Any]]: [('engineer', TelcoFeatureEngineer()), ('preprocessor', ColumnTransformer)]
    """
    all_num, all_cat = get_all_feature_columns()

    num_transformer = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="median")),
            ("scaler", StandardScaler()),
        ]
    )

    cat_transformer = Pipeline(
        steps=[
            ("imputer", SimpleImputer(strategy="most_frequent")),
            ("onehot", OneHotEncoder(handle_unknown="ignore", sparse_output=False)),
        ]
    )

    col_transformer = ColumnTransformer(
        transformers=[
            ("num", num_transformer, all_num),
            ("cat", cat_transformer, all_cat),
        ],
        remainder="drop",
    )

    return [
        ("engineer", TelcoFeatureEngineer()),
        ("preprocessor", col_transformer),
    ]


def build_preprocessing_pipeline() -> Pipeline:
    """Builds the scikit-learn preprocessing Pipeline.

    Integrates:
        - TelcoFeatureEngineer: domain transforms
        - SimpleImputer (median for numeric, most_frequent for categorical)
        - StandardScaler: normalizes numerical distributions
        - OneHotEncoder: encodes discrete categorical features

    Returns:
        Pipeline: Fitted/unfitted composite scikit-learn pipeline.
    """
    return Pipeline(steps=get_preprocessing_steps())


def get_transformed_feature_names(pipeline_or_transformer: Any) -> List[str]:
    """Extracts human-readable feature names from a fitted preprocessing pipeline or ColumnTransformer.

    Args:
        pipeline_or_transformer: Fitted Pipeline or ColumnTransformer.

    Returns:
        List[str]: List of output feature names.
    """
    try:
        if hasattr(pipeline_or_transformer, "named_steps") and "preprocessor" in pipeline_or_transformer.named_steps:
            col_transformer = pipeline_or_transformer.named_steps["preprocessor"]
        elif isinstance(pipeline_or_transformer, ColumnTransformer):
            col_transformer = pipeline_or_transformer
        else:
            col_transformer = pipeline_or_transformer

        feature_names: List[str] = []

        for name, trans, cols in col_transformer.transformers_:
            if name == "remainder" or trans == "drop":
                continue
            if hasattr(trans, "named_steps") and "onehot" in trans.named_steps:
                ohe: OneHotEncoder = trans.named_steps["onehot"]
                cats = ohe.get_feature_names_out(cols)
                feature_names.extend(cats.tolist())
            else:
                feature_names.extend(cols)

        return feature_names
    except Exception as exc:
        logger.warning("Could not extract feature names from pipeline: %s", exc)
        return []
